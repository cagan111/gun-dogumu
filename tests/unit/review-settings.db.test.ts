import { afterAll, expect, it } from "vitest";
try { process.loadEnvFile(".env"); } catch { /* optional local DB */ }
import { prisma } from "@/lib/db";
import { resolveTenantUser } from "@/lib/session";
import { getSettings, settingsSchema, updateSettings } from "@/lib/panel/settings";
import { setAppointmentStatus } from "@/lib/panel/appointments";
import { MemoryQueue, setQueue } from "@/jobs/queue";
const ids: string[] = [];
const url = "https://g.page/r/C_fixture-1/review";
afterAll(async () => { setQueue(null); await prisma.tenant.deleteMany({ where: { id: { in: ids } } }); });
it.skipIf(!process.env.DATABASE_URL)("review config defaults off, owner-only atomic enable/URL invariant and immutable first completion", async () => {
  const tenant = await prisma.tenant.create({ data: { slug: `review-${crypto.randomUUID()}`, name: "Review fixture", city: "Girne", status: "active" } }); ids.push(tenant.id);
  const owner = await prisma.user.create({ data: { tenantId: tenant.id, role: "owner", name: "Owner", email: `${crypto.randomUUID()}@example.test` } });
  const ctx = await resolveTenantUser({ user: { id: owner.id } });
  expect(await getSettings(ctx)).toMatchObject({ reviewInviteEnabled: false, reviewInviteUrl: null });
  await expect(updateSettings({ ...ctx, user: { ...ctx.user, role: "staff" } }, { reviewInviteEnabled: true, reviewInviteUrl: url })).rejects.toMatchObject({ code: "forbidden" });
  await expect(updateSettings(ctx, { reviewInviteEnabled: true })).rejects.toMatchObject({ code: "validation", field: "reviewInviteUrl" });
  await updateSettings(ctx, settingsSchema.parse({ reviewInviteUrl: url }));
  expect(await updateSettings(ctx, { reviewInviteEnabled: true })).toMatchObject({ reviewInviteEnabled: true, reviewInviteUrl: url });
  await expect(updateSettings(ctx, { reviewInviteUrl: null })).rejects.toMatchObject({ code: "validation" });
  expect(await getSettings(ctx)).toMatchObject({ reviewInviteEnabled: true, reviewInviteUrl: url });
  await updateSettings(ctx, { reviewInviteEnabled: false });
  const competing = await Promise.allSettled([updateSettings(ctx, { reviewInviteEnabled: true }), updateSettings(ctx, { reviewInviteUrl: null })]);
  expect(competing.filter(result => result.status === "fulfilled")).toHaveLength(1);
  const merged = await getSettings(ctx); expect(!merged.reviewInviteEnabled || merged.reviewInviteUrl === url).toBe(true);
  await updateSettings(ctx, { reviewInviteEnabled: false, reviewInviteUrl: null });
  await prisma.tenant.update({ where: { id: tenant.id }, data: { status: "suspended" } });
  await expect(updateSettings(ctx, { reviewInviteEnabled: true, reviewInviteUrl: url })).rejects.toMatchObject({ code: "suspended" });
  expect(await getSettings(ctx)).toMatchObject({ reviewInviteEnabled: false, reviewInviteUrl: null });
  await prisma.tenant.update({ where: { id: tenant.id }, data: { status: "active" } });
  expect(await prisma.messageLog.count({ where: { tenantId: tenant.id } })).toBe(0);
  const staff = await prisma.staff.create({ data: { tenantId: tenant.id, name: "Fixture" } });
  const service = await prisma.service.create({ data: { tenantId: tenant.id, nameTr: "Fixture", durationMin: 30, priceTry: "100" } });
  const customer = await prisma.customer.create({ data: { tenantId: tenant.id, name: "Fixture", phone: "+905331234567" } });
  const first = new Date();
  const appointment = await prisma.appointment.create({ data: { tenantId: tenant.id, staffId: staff.id, serviceId: service.id, customerId: customer.id, startsAt: new Date(+first + 21600000), endsAt: new Date(+first + 23400000), blockedUntil: new Date(+first + 23400000), priceTry: "100", cancelToken: crypto.randomUUID() } });
  const queue = new MemoryQueue(); setQueue(queue);
  await setAppointmentStatus(ctx, appointment.id, "completed", first);
  expect((await prisma.appointment.findUniqueOrThrow({ where: { id: appointment.id } })).completedAt).toEqual(first);
  expect(queue.jobs).toHaveLength(0);
  await setAppointmentStatus(ctx, appointment.id, "confirmed", new Date(+first+60000));
  queue.jobs.length = 0;
  await setAppointmentStatus(ctx, appointment.id, "completed", new Date(+first+120000));
  expect((await prisma.appointment.findUniqueOrThrow({ where: { id: appointment.id } })).completedAt).toEqual(first);
  expect(queue.jobs).toHaveLength(0);
  await prisma.appointment.update({ where: { id: appointment.id }, data: { completedAt: null } });
  await setAppointmentStatus(ctx, appointment.id, "completed", new Date(+first+180000));
  expect((await prisma.appointment.findUniqueOrThrow({ where: { id: appointment.id } })).completedAt).toBeNull();
});
